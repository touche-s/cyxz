package com.cyxz.common.base;

import lombok.Getter;

/**
 * 统一错误码枚举
 * <p>6 位编码 = HTTP 状态码(前 3 位) + 业务码(后 3 位)。
 * <ul>
 *   <li>前 3 位复用 HTTP 语义：200 成功 / 400 参数错误 / 401 未认证 / 403 无权限 / 404 资源不存在 / 409 冲突 / 500 系统异常</li>
 *   <li>后 3 位区分业务模块：000 通用 / 100 认证 / 200 帖子 / 300 评论 / 400 圈子 / 500 用户 / 600 消息 / 700 上传</li>
 * </ul>
 * 前端可基于完整 code 做差异化处理，也可通过 {@code code / 1000} 取 HTTP 段。
 */
@Getter
public enum ErrorCode {

    // ==================== 通用段 (000) ====================

    /** 操作成功 */
    SUCCESS(200000, "操作成功"),

    /** 操作失败 */
    FAIL(500000, "操作失败"),

    /** 系统异常 */
    SYSTEM_ERROR(500001, "系统异常"),

    /** 参数错误 */
    PARAM_ERROR(400000, "参数错误"),

    /** 缺少必填参数 */
    PARAM_MISSING(400001, "缺少必填参数"),

    /** 未登录 */
    UNAUTHORIZED(401000, "未登录"),

    /** 缺少 Token */
    TOKEN_MISSING(401001, "缺少Token"),

    /** Token 无效 */
    TOKEN_INVALID(401002, "Token无效"),

    /** 登录已过期 */
    TOKEN_EXPIRED(401003, "登录已过期"),

    /** 没有权限 */
    FORBIDDEN(403000, "没有权限"),

    /** 资源不存在 */
    NOT_FOUND(404000, "资源不存在"),

    /** 资源已存在 */
    ALREADY_EXISTS(409000, "资源已存在"),

    // ==================== 认证模块 (100) ====================

    /** 密码错误 */
    PASSWORD_ERROR(400100, "密码错误"),

    /** 验证码错误 */
    CAPTCHA_ERROR(400101, "验证码错误"),

    /** 验证码已过期 */
    CAPTCHA_EXPIRED(400102, "验证码已过期"),

    /** 账号已被禁用 */
    USER_DISABLED(403100, "账号已被禁用"),

    /** 登录失败次数过多 */
    LOGIN_TOO_MANY(403101, "登录失败次数过多，请稍后再试"),

    /** 用户不存在 */
    USER_NOT_FOUND(404100, "用户不存在"),

    /** 账号已存在 */
    USERNAME_EXISTS(409100, "账号已存在"),

    // ==================== 帖子模块 (200) ====================

    /** 帖子不存在 */
    POST_NOT_FOUND(404200, "帖子不存在"),

    /** 帖子已删除 */
    POST_DELETED(404201, "帖子已删除"),

    /** 帖子审核未通过 */
    POST_REJECTED(404202, "帖子审核未通过"),

    /** 帖子待审核 */
    POST_PENDING(404203, "帖子待审核"),

    /** 帖子状态不可交互（如草稿仅作者可见） */
    POST_NOT_INTERACTABLE(403201, "该帖子不可操作"),

    /** 不是帖子作者 */
    NOT_POST_OWNER(403202, "无权操作该帖子"),

    /** 内容包含敏感词 */
    CONTENT_SENSITIVE(400201, "内容包含敏感词"),

    /** 帖子状态变更非法 */
    POST_STATUS_TRANSITION_INVALID(400202, "帖子状态变更不合法"),

    /** 帖子状态已被修改（并发冲突） */
    POST_STATUS_CONFLICT(400203, "帖子状态已被修改，请刷新后重试"),

    // ==================== 评论模块 (300) ====================

    /** 评论不存在 */
    COMMENT_NOT_FOUND(404300, "评论不存在"),

    /** 父评论不存在 */
    COMMENT_PARENT_NOT_FOUND(404301, "父评论不存在"),

    /** 不支持多级回复 */
    COMMENT_NO_MULTI_LEVEL(400301, "不支持多级回复"),

    /** 不是评论作者或帖子作者 */
    NOT_COMMENT_OWNER(403301, "无权操作该评论"),

    // ==================== 圈子模块 (400) ====================

    /** 圈子不存在 */
    CIRCLE_NOT_FOUND(404400, "圈子不存在"),

    /** 圈子已停用 */
    CIRCLE_DISABLED(403401, "该圈子已停用"),

    /** 未加入圈子 */
    NOT_CIRCLE_MEMBER(403402, "请先加入该圈子"),

    /** 板块模板不存在 */
    SECTION_TEMPLATE_NOT_FOUND(404410, "板块模板不存在"),

    /** 帖子不属于该圈子 */
    POST_NOT_IN_CIRCLE(404401, "帖子不属于该圈子"),

    /** 无权管理圈子成员 */
    NOT_CIRCLE_MANAGER(403403, "无权管理该圈子成员"),

    // ==================== 用户模块 (500) ====================

    /** 不能对自己执行此操作 */
    SELF_OPERATION_FORBIDDEN(403501, "不能对自己执行此操作"),

    // ==================== 消息模块 (600) ====================

    /** 会话不存在 */
    CONVERSATION_NOT_FOUND(404600, "会话不存在"),

    /** 无权操作此会话 */
    NOT_CONVERSATION_MEMBER(403601, "无权操作此会话"),

    /** 需互相关注才能私信 */
    NOT_MUTUAL_FOLLOW(403602, "需要互相关注后才能私信"),

    // ==================== 上传模块 (700) ====================

    /** 文件上传失败 */
    UPLOAD_FAILED(500700, "文件上传失败"),

    /** 文件删除失败 */
    UPLOAD_DELETE_FAILED(500701, "文件删除失败"),

    /** 文件格式不支持 */
    UPLOAD_TYPE_INVALID(400701, "文件格式不支持"),

    /** 文件内容不合法 */
    UPLOAD_CONTENT_INVALID(400702, "文件内容不合法"),

    /** 文件像素过大 */
    UPLOAD_PIXEL_TOO_LARGE(400703, "图片像素过大"),

    ;

    private final int code;
    private final String msg;

    ErrorCode(int code, String msg) {
        this.code = code;
        this.msg = msg;
    }
}
